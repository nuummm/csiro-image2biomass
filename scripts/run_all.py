"""Run the one-axis-at-a-time ablations and write reports/results.md + figures.

Every axis changes a single setting of configs/base.yaml. Backbones whose
embeddings are not cached under emb/ are skipped.

    uv run python scripts/run_all.py
"""

from __future__ import annotations

import argparse
import copy
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from biomass.config import load_config  # noqa: E402
from biomass.data import TARGETS, TOTAL, load_train, targets_matrix  # noqa: E402
from biomass.ensemble import METHODS, ensemble_oof  # noqa: E402
from biomass.metric import r2_per_target  # noqa: E402
from biomass.pipeline import emb_file, load_run, run_experiment, run_name  # noqa: E402

AXES = {
    "CV scheme": ("cv.scheme", ["kfold", "group_date", "group_month_state"]),
    "Backbone": ("backbone", ["dinov3_large", "siglip_so400m", "color_stats"]),
    "Head": ("model.head", ["ridge", "lgbm"]),
    "Target space": ("model.target_space", ["raw", "log1p"]),
    "Output formulation": ("model.formulation", ["independent", "sum", "diff", "nnls"]),
}
INK, MUTED, BAR = "#1f2328", "#6e7781", "#3b6ea8"


def set_path(cfg: dict, dotted: str, value) -> dict:
    cfg = copy.deepcopy(cfg)
    *parents, leaf = dotted.split(".")
    node = cfg
    for p in parents:
        node = node[p]
    node[leaf] = value
    return cfg


def get_run(cfg: dict, cache: dict, rerun: bool) -> dict | None:
    name = run_name(cfg)
    if name in cache:
        return cache[name]
    if not emb_file(cfg["emb_dir"], cfg["backbone"], "train").exists():
        print(f"skip {name}: no cached embeddings")
        return None
    run_dir = Path(cfg["runs_dir"]) / name
    try:
        if rerun or not (run_dir / "summary.json").exists():
            print(f"run  {name}", flush=True)
            run_experiment(cfg, name=name)
    except ValueError as err:  # e.g. fewer groups than folds
        print(f"skip {name}: {err}")
        return None
    cache[name] = load_run(run_dir)
    return cache[name]


def fmt(mean: float, std: float) -> str:
    return f"{mean:.4f} ± {std:.4f}"


def dot_figure(labels, means, stds, title, path: Path) -> None:
    """Point + whisker (mean +/- std); a dot plot keeps a zoomed axis honest, unlike bars."""
    fig, ax = plt.subplots(figsize=(6, 0.6 + 0.45 * len(labels)))
    y = np.arange(len(labels))
    ax.errorbar(means, y, xerr=stds, fmt="o", color=BAR, ecolor=INK, elinewidth=1, capsize=3, ms=6)
    ax.set_yticks(y, labels, color=INK)
    ax.set_ylim(len(labels) - 0.5, -0.5)
    ax.set_xlabel("OOF weighted R² (mean ± std over seeds)", color=MUTED)
    ax.set_title(title, loc="left", color=INK)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.grid(axis="x", color="#d0d7de", lw=0.6)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def calibration_total(y_true: np.ndarray, y_pred: np.ndarray, path: Path, n_bins: int = 10) -> None:
    """Mean truth vs mean OOF prediction per prediction decile (no per-image labels shown)."""
    order = np.argsort(y_pred)
    bins = np.array_split(order, n_bins)
    pred_mean = np.array([y_pred[b].mean() for b in bins])
    true_mean = np.array([y_true[b].mean() for b in bins])
    fig, ax = plt.subplots(figsize=(4.5, 4.5))
    hi = float(max(pred_mean.max(), true_mean.max())) * 1.1
    ax.plot([0, hi], [0, hi], color=MUTED, lw=1, ls="--")
    ax.plot(pred_mean, true_mean, "o-", color=BAR, ms=5, lw=1)
    ax.set_xlim(0, hi)
    ax.set_ylim(0, hi)
    ax.set_xlabel("mean OOF prediction, Dry_Total_g", color=MUTED)
    ax.set_ylabel("mean true value", color=MUTED)
    ax.set_title(f"Base config, first seed ({n_bins} bins)", loc="left", color=INK)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--config", default="configs/base.yaml")
    ap.add_argument("--set", action="append", default=[])
    ap.add_argument("--report-dir", default="reports")
    ap.add_argument("--rerun", action="store_true", help="ignore existing run directories")
    args = ap.parse_args(argv)

    base = load_config(args.config, args.set)
    report_dir = Path(args.report_dir)
    fig_dir = report_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    cache: dict = {}
    lines = [
        "# Results",
        "",
        "Generated by `scripts/run_all.py`. Scores are the competition metric (global weighted R²)",
        "on out-of-fold predictions, mean ± std over the CV seeds of `configs/base.yaml`.",
        "",
        f"Base configuration: `{run_name(base)}`, {base['cv']['n_splits']} folds, "
        f"seeds {base['cv']['seeds']}.",
        "",
    ]

    for title, (path, values) in AXES.items():
        rows = []
        for v in values:
            run = get_run(set_path(base, path, v), cache, args.rerun)
            if run is not None:
                rows.append((str(v), run["summary"]))
        if not rows:
            continue
        lines += [
            f"## {title}",
            "",
            f"| {path} | OOF R² | fold R² | R² Total |",
            "|---|---|---|---|",
        ]
        for v, s in rows:
            lines.append(
                f"| {v} | {fmt(s['oof_score_mean'], s['oof_score_std'])} | "
                f"{fmt(s['fold_score_mean'], s['fold_score_std'])} | "
                f"{s['r2_per_target'][TOTAL]:.4f} |"
            )
        lines.append("")
        slug = title.lower().replace(" ", "_")
        dot_figure(
            [v for v, _ in rows],
            [s["oof_score_mean"] for _, s in rows],
            [s["oof_score_std"] for _, s in rows],
            title,
            fig_dir / f"{slug}.png",
        )
        lines += [f"![{title}](figures/{slug}.png)", ""]

    base_run = get_run(base, cache, args.rerun)
    if base_run is not None:
        train = load_train(base.get("data_dir"))
        Y = targets_matrix(train)
        first = next(iter(base_run["oof"]))
        per_t = r2_per_target(Y, base_run["oof"][first])
        lines += ["## Per-target R² (base config, first seed)", ""]
        lines += ["| " + " | ".join(TARGETS) + " |", "|" + "---|" * len(TARGETS)]
        lines += ["| " + " | ".join(f"{per_t[t]:.4f}" for t in TARGETS) + " |", ""]
        calibration_total(
            Y[:, TARGETS.index(TOTAL)],
            base_run["oof"][first][:, TARGETS.index(TOTAL)],
            fig_dir / "oof_total_binned.png",
        )
        lines += ["![Binned OOF calibration for Total](figures/oof_total_binned.png)", ""]

        members = [
            r
            for r in cache.values()
            if r["folds"].equals(base_run["folds"])
            and r["config"]["cv"]["scheme"] == base["cv"]["scheme"]
            and r["config"]["model"]["formulation"] == base["model"]["formulation"]
        ]
        if len(members) >= 2:
            lines += [
                "## Ensembling",
                "",
                "Members: " + ", ".join(f"`{m['dir'].name}`" for m in members),
                "",
            ]
            lines += ["| method | OOF R² | weights (full fit, first seed) |", "|---|---|---|"]
            for method in METHODS:
                res = [
                    ensemble_oof(
                        [m["oof"][c] for m in members], Y, base_run["folds"][c].to_numpy(), method
                    )
                    for c in base_run["folds"].columns
                ]
                scores = [r["score"] for r in res]
                w = ", ".join(f"{x:.3f}" for x in res[0]["weights"])
                lines.append(f"| {method} | {fmt(np.mean(scores), np.std(scores))} | {w} |")
            lines.append("")

    out = report_dir / "results.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
